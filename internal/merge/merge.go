// Package merge turns the exports of several Swarms (for example
// development, acceptance and production) into one Kustomize base with
// the manifests they share and a per-environment overlay that holds only
// what differs: objects that exist in some environments only, and
// standard kustomize patches for the rest. Stock Flux2 and flux4swarm
// build the result the same way, and every overlay builds back to exactly
// the environment it came from.
package merge

import (
	"bytes"
	"encoding/json"
	"fmt"
	"path"
	"reflect"
	"sort"
	"strings"

	"sigs.k8s.io/kustomize/api/krusty"
	"sigs.k8s.io/kustomize/api/types"
	"sigs.k8s.io/kustomize/kyaml/filesys"
	"sigs.k8s.io/yaml"

	"github.com/olljanat-ai/flux4swarm/internal/api"
	"github.com/olljanat-ai/flux4swarm/internal/importer"
)

// DefaultBasePath is where the shared manifests go.
const DefaultBasePath = "apps/base"

const header = "# Generated by flux4swarm merge.\n"

// Env is the built manifests of one environment.
type Env struct {
	// Name of the environment (development, production...).
	Name string
	// Path is the environment's apps directory (clusters/<name>/apps),
	// which becomes its overlay.
	Path string
	// Objects are the environment's objects, as a kustomize build of its
	// apps directory returns them.
	Objects []map[string]any
}

// Options configures Merge.
type Options struct {
	// BasePath is the shared base directory, relative to the repository
	// root (default apps/base).
	BasePath string
}

// object is one manifest with its identity.
type object struct {
	key  string
	gvk  gvk
	ns   string
	name string
	obj  map[string]any
}

type gvk struct{ group, version, kind string }

func (g gvk) apiVersion() string {
	if g.group == "" {
		return g.version
	}
	return g.group + "/" + g.version
}

func newObject(m map[string]any) (object, error) {
	m = normalize(m).(map[string]any)
	av, _ := m["apiVersion"].(string)
	kind, _ := m["kind"].(string)
	meta, _ := m["metadata"].(map[string]any)
	name, _ := meta["name"].(string)
	ns, _ := meta["namespace"].(string)
	if av == "" || kind == "" || name == "" {
		return object{}, fmt.Errorf("object without apiVersion, kind or metadata.name")
	}
	g := gvk{version: av, kind: kind}
	if grp, ver, ok := strings.Cut(av, "/"); ok {
		g.group, g.version = grp, ver
	}
	return object{key: g.group + "/" + kind + "/" + ns + "/" + name, gvk: g, ns: ns, name: name, obj: m}, nil
}

// file is the file name of an object inside a namespace directory.
func (o object) file() string {
	if o.gvk.kind == "Namespace" && o.gvk.group == "" {
		return "namespace.yaml"
	}
	return strings.ToLower(o.gvk.kind) + "-" + o.name + ".yaml"
}

// dir is the directory of an object, relative to the base or overlay:
// its namespace, the namespace itself for Namespace objects, and the
// root for other cluster-scoped objects.
func (o object) dir() string {
	if o.gvk.kind == "Namespace" && o.gvk.group == "" {
		return o.name
	}
	return o.ns
}

// Merge computes the base and the overlays. Each environment's Path is
// emptied and rewritten, as is the base; the result lists them in Clean.
func Merge(envs []Env, o Options) (*importer.Result, error) {
	if len(envs) < 2 {
		return nil, fmt.Errorf("merge needs at least two environments")
	}
	if o.BasePath == "" {
		o.BasePath = DefaultBasePath
	}
	o.BasePath = cleanPath(o.BasePath)
	seenName, seenPath := map[string]bool{}, map[string]bool{}
	for i := range envs {
		envs[i].Path = cleanPath(envs[i].Path)
		e := envs[i]
		if e.Name == "" || seenName[e.Name] {
			return nil, fmt.Errorf("environment names must be unique and not empty")
		}
		if e.Path == "" || e.Path == "." || strings.HasPrefix(e.Path, "..") || seenPath[e.Path] {
			return nil, fmt.Errorf("environment %s: invalid or duplicate path %q", e.Name, e.Path)
		}
		if within(e.Path, o.BasePath) || within(o.BasePath, e.Path) {
			return nil, fmt.Errorf("environment %s: path %s overlaps the base %s", e.Name, e.Path, o.BasePath)
		}
		seenName[e.Name], seenPath[e.Path] = true, true
	}

	// Index every environment's objects.
	n := len(envs)
	byEnv := make([]map[string]object, n)
	var keys []string
	count := map[string]int{}
	for i, e := range envs {
		byEnv[i] = map[string]object{}
		for _, m := range e.Objects {
			obj, err := newObject(m)
			if err != nil {
				return nil, fmt.Errorf("environment %s: %w", e.Name, err)
			}
			if _, dup := byEnv[i][obj.key]; dup {
				return nil, fmt.Errorf("environment %s: duplicate object %s", e.Name, obj.key)
			}
			byEnv[i][obj.key] = obj
			if count[obj.key] == 0 {
				keys = append(keys, obj.key)
			}
			count[obj.key]++
		}
	}
	sort.Strings(keys)

	res := &importer.Result{Files: map[string][]byte{}, Root: o.BasePath}
	res.Clean = append(res.Clean, o.BasePath)
	base := newTree(o.BasePath)
	overlays := make([]*overlay, n)
	for i, e := range envs {
		res.Clean = append(res.Clean, e.Path)
		overlays[i] = &overlay{tree: newTree(e.Path)}
	}

	for _, k := range keys {
		if count[k] < n {
			// Only some environments have it: each keeps its own copy.
			for i := range envs {
				if obj, ok := byEnv[i][k]; ok {
					overlays[i].add(obj, obj.obj)
				}
			}
			continue
		}
		vals := make([]any, n)
		var any0 object
		for i := range envs {
			vals[i] = byEnv[i][k].obj
			any0 = byEnv[i][k]
		}
		common, _ := pick(vals, n)
		cm, _ := common.(map[string]any)
		if cm == nil {
			cm = map[string]any{}
		}
		// The identity always stays in the base.
		ident(cm, any0)
		base.add(any0, cm)
		for i, e := range envs {
			target := byEnv[i][k]
			if reflect.DeepEqual(cm, target.obj) {
				continue
			}
			p, err := patchFor(cm, target)
			if err != nil {
				return nil, fmt.Errorf("environment %s: %s: %w", e.Name, k, err)
			}
			overlays[i].patches = append(overlays[i].patches, p)
		}
	}

	if err := base.render(res.Files); err != nil {
		return nil, err
	}
	for i, e := range envs {
		rel, err := relPath(e.Path, o.BasePath)
		if err != nil {
			return nil, err
		}
		if err := overlays[i].render(res.Files, rel); err != nil {
			return nil, err
		}
	}

	// Every overlay must build back to exactly its environment, with the
	// load restrictions of a stock kustomize build.
	for i, e := range envs {
		got, err := buildFiles(res.Files, e.Path)
		if err != nil {
			return nil, fmt.Errorf("environment %s: overlay does not build: %w", e.Name, err)
		}
		if err := sameObjects(byEnv[i], got); err != nil {
			return nil, fmt.Errorf("environment %s: overlay does not match the export: %w", e.Name, err)
		}
	}
	for i, e := range envs {
		res.Notes = append(res.Notes, fmt.Sprintf("%s: %d shared object(s) patched, %d object(s) only in this environment",
			e.Name, len(overlays[i].patches), len(overlays[i].own)))
	}
	return res, nil
}

func ident(cm map[string]any, o object) {
	cm["apiVersion"] = o.gvk.apiVersion()
	cm["kind"] = o.gvk.kind
	meta, _ := cm["metadata"].(map[string]any)
	if meta == nil {
		meta = map[string]any{}
	}
	meta["name"] = o.name
	if o.ns != "" {
		meta["namespace"] = o.ns
	}
	cm["metadata"] = meta
}

// tree is a directory of manifests with a kustomization.yaml per
// directory, the same layout import writes.
type tree struct {
	root  string
	files map[string]map[string]any // relative file -> object
	order []string
	own   []string
}

func newTree(root string) *tree { return &tree{root: root, files: map[string]map[string]any{}} }

func (t *tree) add(o object, content map[string]any) {
	f := o.file()
	if d := o.dir(); d != "" {
		f = d + "/" + f
	}
	if _, taken := t.files[f]; taken {
		ext := path.Ext(f)
		for i := 2; ; i++ {
			alt := strings.TrimSuffix(f, ext) + "-" + fmt.Sprint(i) + ext
			if _, taken := t.files[alt]; !taken {
				f = alt
				break
			}
		}
	}
	t.files[f] = content
	t.order = append(t.order, f)
	t.own = append(t.own, f)
}

// render writes the objects and the kustomization.yaml files.
func (t *tree) render(out map[string][]byte) error {
	dirs := map[string][]string{}
	for _, f := range t.order {
		dirs[path.Dir(f)] = append(dirs[path.Dir(f)], path.Base(f))
		b, err := marshal(t.files[f])
		if err != nil {
			return err
		}
		out[t.root+"/"+f] = b
	}
	var sub []string
	for d, files := range dirs {
		if d == "." {
			continue
		}
		sort.Strings(files)
		b, err := marshal(kustomization(files))
		if err != nil {
			return err
		}
		out[t.root+"/"+d+"/kustomization.yaml"] = b
		sub = append(sub, d)
	}
	sort.Strings(sub)
	rootFiles := append([]string(nil), dirs["."]...)
	sort.Strings(rootFiles)
	b, err := marshal(kustomization(append(rootFiles, sub...)))
	if err != nil {
		return err
	}
	out[t.root+"/kustomization.yaml"] = b
	return nil
}

// overlay is one environment: its own objects plus patches on the base.
type overlay struct {
	*tree
	patches []patch
}

type patch struct {
	obj object
	smp map[string]any // strategic merge patch, or
	ops []jsonOp       // JSON6902 operations
}

func (ov *overlay) render(out map[string][]byte, basePath string) error {
	var entries []any
	used := map[string]bool{}
	for f := range ov.files {
		used[f] = true
	}
	for _, p := range ov.patches {
		f := strings.TrimSuffix(p.obj.file(), ".yaml") + "-patch.yaml"
		if d := p.obj.dir(); d != "" {
			f = d + "/" + f
		}
		for i := 2; used[f]; i++ {
			f = strings.TrimSuffix(f, "-patch.yaml") + fmt.Sprint(i) + "-patch.yaml"
		}
		used[f] = true
		var b []byte
		var err error
		entry := map[string]any{"path": f}
		if p.ops != nil {
			b, err = marshal(p.ops)
			entry["target"] = patchTarget(p.obj)
		} else {
			b, err = marshal(p.smp)
		}
		if err != nil {
			return err
		}
		out[ov.root+"/"+f] = b
		entries = append(entries, entry)
	}
	// Own objects are listed in the root kustomization (no kustomization
	// per directory), so the patch files next to them are not resources.
	own := append([]string(nil), ov.own...)
	sort.Strings(own)
	k := kustomization(append([]string{basePath}, own...))
	if len(entries) > 0 {
		k["patches"] = entries
	}
	for _, f := range ov.order {
		b, err := marshal(ov.files[f])
		if err != nil {
			return err
		}
		out[ov.root+"/"+f] = b
	}
	b, err := marshal(k)
	if err != nil {
		return err
	}
	out[ov.root+"/kustomization.yaml"] = b
	return nil
}

func patchTarget(o object) map[string]any {
	t := map[string]any{"version": o.gvk.version, "kind": o.gvk.kind, "name": o.name}
	if o.gvk.group != "" {
		t["group"] = o.gvk.group
	}
	if o.ns != "" {
		t["namespace"] = o.ns
	}
	return t
}

func kustomization(resources []string) map[string]any {
	return map[string]any{
		"apiVersion": "kustomize.config.k8s.io/v1beta1",
		"kind":       "Kustomization",
		"resources":  resources,
	}
}

func marshal(v any) ([]byte, error) {
	b, err := yaml.Marshal(v)
	if err != nil {
		return nil, err
	}
	return append([]byte(header), b...), nil
}

// patchFor returns a strategic merge patch from base to target when
// kustomize applies it exactly, else an exact JSON6902 patch.
func patchFor(base map[string]any, target object) (patch, error) {
	p := patch{obj: target}
	if d, ok := smpDiff(base, target.obj); ok {
		dm, _ := d.(map[string]any)
		if dm == nil {
			dm = map[string]any{}
		}
		ident(dm, target)
		got, err := applyPatch(base, map[string]any{"path": "patch.yaml"}, dm)
		if err == nil && reflect.DeepEqual(got, target.obj) {
			p.smp = dm
			return p, nil
		}
	}
	p.ops = jsonDiff(base, target.obj, "", nil)
	got, err := applyPatch(base, map[string]any{"path": "patch.yaml", "target": patchTarget(target)}, p.ops)
	if err != nil {
		return p, err
	}
	if !reflect.DeepEqual(got, target.obj) {
		return p, fmt.Errorf("cannot express the difference as a kustomize patch")
	}
	return p, nil
}

// applyPatch builds base with one patch in memory.
func applyPatch(base map[string]any, entry map[string]any, p any) (map[string]any, error) {
	fs := filesys.MakeFsInMemory()
	for f, v := range map[string]any{
		"/k/base.yaml":          base,
		"/k/patch.yaml":         p,
		"/k/kustomization.yaml": map[string]any{"resources": []string{"base.yaml"}, "patches": []any{entry}},
	} {
		b, err := yaml.Marshal(v)
		if err != nil {
			return nil, err
		}
		if err := fs.WriteFile(f, b); err != nil {
			return nil, err
		}
	}
	rm, err := krusty.MakeKustomizer(krusty.MakeDefaultOptions()).Run(fs, "/k")
	if err != nil {
		return nil, err
	}
	if len(rm.Resources()) != 1 {
		return nil, fmt.Errorf("patch produced %d objects", len(rm.Resources()))
	}
	m, err := rm.Resources()[0].Map()
	if err != nil {
		return nil, err
	}
	return normalize(m).(map[string]any), nil
}

// buildFiles builds dir of files with stock kustomize options (load
// restricted to the kustomization root, like `kustomize build`).
func buildFiles(files map[string][]byte, dir string) ([]map[string]any, error) {
	fs := filesys.MakeFsInMemory()
	for f, b := range files {
		if err := fs.WriteFile("/"+f, b); err != nil {
			return nil, err
		}
	}
	ko := krusty.MakeDefaultOptions()
	ko.LoadRestrictions = types.LoadRestrictionsRootOnly
	rm, err := krusty.MakeKustomizer(ko).Run(fs, "/"+dir)
	if err != nil {
		return nil, err
	}
	var out []map[string]any
	for _, r := range rm.Resources() {
		m, err := r.Map()
		if err != nil {
			return nil, err
		}
		out = append(out, m)
	}
	return out, nil
}

func sameObjects(want map[string]object, got []map[string]any) error {
	seen := map[string]bool{}
	for _, m := range got {
		o, err := newObject(m)
		if err != nil {
			return err
		}
		w, ok := want[o.key]
		if !ok {
			return fmt.Errorf("unexpected object %s", o.key)
		}
		if !reflect.DeepEqual(w.obj, o.obj) {
			return fmt.Errorf("object %s differs", o.key)
		}
		seen[o.key] = true
	}
	for k := range want {
		if !seen[k] {
			return fmt.Errorf("missing object %s", k)
		}
	}
	return nil
}

// Load decodes the multi-document YAML of a kustomize build.
func Load(data []byte) ([]map[string]any, error) {
	var out []map[string]any
	for _, doc := range api.SplitYAML(data) {
		if len(bytes.TrimSpace(doc)) == 0 {
			continue
		}
		var m map[string]any
		if err := yaml.Unmarshal(doc, &m); err != nil {
			return nil, err
		}
		if len(m) > 0 {
			out = append(out, m)
		}
	}
	return out, nil
}

// normalize turns any decoded value into plain JSON types.
func normalize(v any) any {
	b, err := json.Marshal(v)
	if err != nil {
		return v
	}
	var out any
	if err := json.Unmarshal(b, &out); err != nil {
		return v
	}
	return out
}

func cleanPath(p string) string {
	return strings.Trim(path.Clean("/"+strings.TrimPrefix(p, "./")), "/")
}

func within(p, dir string) bool { return p == dir || strings.HasPrefix(p, dir+"/") }

// relPath is the slash path from dir to target.
func relPath(dir, target string) (string, error) {
	d, t := strings.Split(dir, "/"), strings.Split(target, "/")
	i := 0
	for i < len(d) && i < len(t) && d[i] == t[i] {
		i++
	}
	var parts []string
	for range d[i:] {
		parts = append(parts, "..")
	}
	parts = append(parts, t[i:]...)
	if len(parts) == 0 {
		return "", fmt.Errorf("base and overlay are the same directory")
	}
	return strings.Join(parts, "/"), nil
}
